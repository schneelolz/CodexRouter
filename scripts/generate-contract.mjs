import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { existsSync } from 'node:fs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const spec = JSON.parse(readFileSync(path.join(root, 'contracts/openapi.json'), 'utf8'))
const schemas = spec.components.schemas
const initialisms = new Map(['id', 'url', 'api', 'csrf', 'ms'].map(x => [x, x.toUpperCase()]))
const goName = key => key.split('_').map(x => initialisms.get(x) ?? x[0].toUpperCase() + x.slice(1)).join('')

function typeOf(schema, language) {
  if (schema.$ref) {
    const name = schema.$ref.replace('#/components/schemas/', '')
    if (!schemas[name]) throw new Error(`Unknown schema ${name}`)
    return name
  }
  if (schema.enum && language === 'ts') return schema.enum.map(x => JSON.stringify(x)).join(' | ')
  if (schema.type === 'array') return language === 'go' ? `[]${typeOf(schema.items, language)}` : `Array<${typeOf(schema.items, language)}>`
  if (schema.type === 'string') return 'string'
  if (schema.type === 'integer') return language === 'go' ? 'int' : 'number'
  if (schema.type === 'boolean') return language === 'go' ? 'bool' : 'boolean'
  throw new Error(`Unsupported schema: ${JSON.stringify(schema)}`)
}

let go = '// Code generated by scripts/generate-contract.mjs. DO NOT EDIT.\n\npackage api\n\n'
let ts = '// 由 scripts/generate-contract.mjs 生成，请勿手改。\n\n'
for (const [name, schema] of Object.entries(schemas)) {
  go += `// ${name} ${schema.description ?? '定义管理 API 的公开数据。'}\n`
  if (schema.type === 'object') {
    if (schema.additionalProperties !== false) throw new Error(`${name} must disallow unknown fields`)
    go += `type ${name} struct {\n`
    ts += `/** ${schema.description ?? name} */\nexport interface ${name} {\n`
    for (const [key, property] of Object.entries(schema.properties)) {
      const required = schema.required.includes(key)
      if (!required) throw new Error(`Optional property not supported: ${name}.${key}`)
      go += `\t// ${goName(key)} ${property.description ?? '定义对应字段。'}\n\t${goName(key)} ${typeOf(property, 'go')} \`json:"${key}"\`\n`
      ts += `  ${key}: ${typeOf(property, 'ts')}\n`
    }
    go += '}\n\n'
    ts += '}\n\n'
  } else {
    go += `type ${name} ${typeOf(schema, 'go')}\n\n`
    ts += `export type ${name} = ${typeOf(schema, 'ts')}\n\n`
    if (schema.enum) {
      go += 'const (\n'
      for (const value of schema.enum) go += `\t// ${name}${goName(value)} 表示${value}。\n\t${name}${goName(value)} ${name} = ${JSON.stringify(value)}\n`
      go += ')\n\n'
    }
  }
}
const localGofmt = path.join(process.env.LOCALAPPDATA ?? '', 'CodexRouter/toolchains/go/bin/gofmt.exe')
const gofmt = process.env.GOFMT ?? (existsSync(localGofmt) ? localGofmt : 'gofmt')
go = execFileSync(gofmt, [], { input: go, encoding: 'utf8' }).replace(/\r\n/g, '\n')
const outputs = [['internal/api/types.gen.go', go], ['frontend/src/api/types.gen.ts', ts.trimEnd() + '\n']]
let changed = false
for (const [relative, text] of outputs) {
  const filename = path.join(root, relative)
  if (process.argv.includes('--check')) {
    if (readFileSync(filename, 'utf8').replace(/\r\n/g, '\n') !== text) {
      console.error(`Generated contract differs: ${relative}`)
      changed = true
    }
  } else {
    mkdirSync(path.dirname(filename), { recursive: true })
    writeFileSync(filename, text)
  }
}
if (changed) process.exitCode = 1
